def main() -> int:
    with PATH.open(encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh); rows = list(reader); fields = list(reader.fieldnames or [])
    by_id = {r.get("id", ""): r for r in rows}; added = updated = 0
    for aid, title, primary, secondary, basis, note in SPEC:
        row = {"id": aid, "title": title, "primary_print_topic_code": primary,
               "secondary_print_topic_codes": secondary, "classification_status": "manual_confirmed",
               "decision_basis": basis, "review_note": note, "reviewer": "main-thread", "reviewed_at": "2026-09-23"}
        if aid in by_id:
            if by_id[aid] != row: by_id[aid].update(row); updated += 1
        else: rows.append(row); by_id[aid] = row; added += 1
    with PATH.open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields); w.writeheader(); w.writerows(rows)
    print(f"added={added} updated={updated} rows={len(rows)}")

if __name__ == "__main__": raise SystemExit(main())
