def lcs_len(a, b):
    # longest common substring length (a small, b large) -> use suffix automaton-ish DP over a
    if not a or not b: return 0
    best = 0
    prev = [0]*(len(b)+1)
    for i in range(1, len(a)+1):
        cur = [0]*(len(b)+1)
        ai = a[i-1]
        for j in range(1, len(b)+1):
            if ai == b[j-1]:
                cur[j] = prev[j-1] + 1
                if cur[j] > best: best = cur[j]
        prev = cur
    return best

