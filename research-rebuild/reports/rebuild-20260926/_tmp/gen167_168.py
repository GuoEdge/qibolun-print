ROUNDS = [('round167', D167, 'subagent+round167-body-review'),
          ('round168', D168, 'subagent+round168-body-review')]

BLOCK_OK = {'source_empty','source_truncated','body_is_quotation','body_is_pointer',
            'body_question_mismatch','body_too_short_for_center','a00_registry_gap'}

report_checks = {}

for rnd, D, reviewer in ROUNDS:
    rdir = os.path.join(BASE, rnd)
    arts = json.load(open(os.path.join(rdir, f'{rnd}-fulltext.json'), encoding='utf-8'))
    sel = list(csv.DictReader(open(os.path.join(rdir, f'{rnd}-selection.csv'), encoding='utf-8-sig')))
    selby = {r['id']: r for r in sel}
    assert len(arts) == len(sel), (len(arts), len(sel))
    assert set(a['id'] for a in arts) == set(selby), 'ID set mismatch'

    dec_rows, aud_rows, rev_rows, checks = [], [], [], []
    total_chars = 0
    for a in arts:
        t = a['title']; text = a['text']; total_chars += len(text)
        assert t in D, t
        np_, ns_, st, br, quote, reason, risk = D[t]
        s = selby[a['id']]
        op, os_ = a.get('manual_primary') or '', a.get('manual_secondary') or ''
        ost = a.get('manual_status') or ''
        nss = ';'.join(ns_)
        # checks
        nq, nt = norm(quote), norm(text)
        hit_exact = (nq in nt) and len(nq) >= 12
        lc = lcs_len(nq, nt)
        assert quote in text, ('quote not verbatim', t)
        checks.append((t, len(nq), hit_exact, lc))
        assert hit_exact, ('quote norm fail', t)
        assert lc >= 12, ('lcs fail', t)
        codes = [np_] + ns_
        assert all(c in REG for c in codes), ('bad code', t, codes)
        assert np_ not in ns_, ('primary in secondary', t)
        assert len(ns_) <= 3
        if st == 'manual_provisional':
            assert br in BLOCK_OK, ('bad blocking', t, br)
        else:
            assert br == '', ('blocking must be empty when confirmed', t)

        dec_rows.append({'id': a['id'], 'title': t, 'primary': np_, 'secondary': nss,
                         'status': st, 'basis': reason, 'risk_note': risk})
        aud_rows.append({'id': a['id'], 'title': t, 'source_ordinal': s.get('source_ordinal',''),
                         'body_char_count': len(text), 'old_primary': op, 'old_secondary': os_,
                         'old_status': ost, 'new_primary': np_, 'new_secondary': nss,
                         'new_status': st, 'blocking_reason': br, 'body_evidence_quote': quote,
                         'decision_reason': reason, 'reviewer': reviewer, 'reviewed_at': '2026-09-26'})
        if (op, os_, ost) != (np_, nss, st):
            rev_rows.append({'id': a['id'], 'title': t, 'old_primary': op, 'old_secondary': os_,
                             'old_status': ost, 'new_primary': np_, 'new_secondary': nss,
                             'new_status': st, 'basis': reason, 'risk_note': risk,
                             'revision_source': f'{rnd}-decisions.tsv (body reread)',
                             'revised_at': '2026-09-26'})

    def wtsv(path, rows, cols):
        with open(path, 'w', newline='', encoding='utf-8') as f:
            w = csv.DictWriter(f, fieldnames=cols, delimiter='\t', quoting=csv.QUOTE_MINIMAL)
            w.writeheader()
            for r in rows: w.writerow(r)
    def wcsv(path, rows, cols):
        with open(path, 'w', newline='', encoding='utf-8') as f:
            w = csv.DictWriter(f, fieldnames=cols, quoting=csv.QUOTE_MINIMAL)
            w.writeheader()
            for r in rows: w.writerow(r)

    wtsv(os.path.join(rdir, f'{rnd}-decisions.tsv'), dec_rows,
         ['id','title','primary','secondary','status','basis','risk_note'])
    wtsv(os.path.join(rdir, f'{rnd}-body-evidence-audit.tsv'), aud_rows,
         ['id','title','source_ordinal','body_char_count','old_primary','old_secondary','old_status',
          'new_primary','new_secondary','new_status','blocking_reason','body_evidence_quote',
          'decision_reason','reviewer','reviewed_at'])
    wcsv(os.path.join(rdir, f'{rnd}-revision-log.csv'), rev_rows,
         ['id','title','old_primary','old_secondary','old_status','new_primary','new_secondary',
          'new_status','basis','risk_note','revision_source','revised_at'])

    nconf = sum(1 for r in dec_rows if r['status'] == 'manual_confirmed')
    nprov = sum(1 for r in dec_rows if r['status'] == 'manual_provisional')
    prim_ch = [(r['title'], r['old_primary'], r['new_primary']) for r in rev_rows if r['old_primary'] != r['new_primary']]
    sec_ch = [(r['title'], r['old_secondary'], r['new_secondary']) for r in rev_rows if r['old_secondary'] != r['new_secondary']]
    report_checks[rnd] = dict(n=len(arts), total_chars=total_chars, nconf=nconf, nprov=nprov,
                              prim_ch=prim_ch, sec_ch=sec_ch, rev=len(rev_rows),
                              checks=checks, minlen=min(len(a['text']) for a in arts),
                              maxlen=max(len(a['text']) for a in arts))
    print(rnd, 'rows', len(arts), 'chars', total_chars, 'confirmed', nconf, 'provisional', nprov,
          'primary_changes', prim_ch, 'secondary_changes', len(sec_ch), 'revlog', len(rev_rows))

json.dump(report_checks, open(os.path.join(BASE, '_tmp', 'checks.json'), 'w', encoding='utf-8'),
          ensure_ascii=False, indent=1)
