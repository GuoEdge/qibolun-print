#!/usr/bin/env python3
"""
岐伯论·卷一（血亲宗族与家庭抚育）全量通读与主题契合度深度审查脚本
严格要求：
1. 逐篇全文通读，把握提问情境、岐伯回答的实质论点与解决的实际问题。
2. 绝不使用关键词匹配，做实质性内容审查。
3. 审查两个层次：
   - 层次一：该文章是否属于卷一（血亲宗族与家庭抚育 / 本根敦伦）？还是更应属于其他卷（V2两性、V3熟人处世、V4身心修养、V5职场商业、V6时代社会、V7哲学思辨、V8史地政制）？
   - 层次二：若属于卷一，其内容是否契合当前所在的分册（B01~B10）？是否存在分册错置（如B01混入大学中考功课、B06混入幼童教育等）？
"""

import json
import re

with open('v1_full_reading_corpus.json', 'r', encoding='utf-8') as f:
    corpus = json.load(f)

# V1 包含的 10 个分册主题定位：
# B01 (甲册): 幼儿启蒙与性情习惯 - 婴幼儿至学龄前幼童、习惯养成、童年情趣、启蒙感知、基础生活习惯
# B02 (乙册): 学业功课与学校日常 - 中小学/大学课业学习、升学考试、学科方法、学校师生同侪交往、作业成绩
# B03 (丙册): 言传身教与奖惩边界 - 父母日常管教、家规设立、奖惩原则、身教示范、不良恶习纠正
# B04 (丁册): 亲子沟通与青春叛逆 - 青春期反叛、两代沟通鸿沟、情感疏导、倾听与平等对话、自主权博弈
# B05 (戊册): 父母控制欲与精神解绑 - 窒息式沉重母爱/父权、过度干涉控制、子女心理断乳与精神自主、化解原生家庭心理创伤
# B06 (己册): 成年子女自立与边界 - 成年后与父母的物理/经济/生活边界、带娃与养老博弈、催婚催育应对、经济独立
# B07 (庚册): 隔代教养与长辈相处 - 祖辈参与育儿观念冲突、隔代溺爱协调、孝敬与侍奉祖父母
# B08 (辛册): 手足同胞与家族亲戚 - 兄弟姐妹同侪竞争与关爱、家族亲戚走动、亲戚间借钱利益纠葛与人情
# B09 (壬册): 家族传承与家风家范 - 家族兴衰、家风门风建设、家族资源跨代积累与传递、家训
# B10 (癸册): 临终关怀与白事奠仪 - 老人重病照料、临终告别、丧葬礼俗白事、祭祀追思、面对至亲死亡

results = []

for item in corpus:
    aid = item['id']
    title = item['title']
    bc = item['booklet_code']
    bn = item['booklet_name']
    q = item['question']
    txt = item['text']
    
    # 记录待分析条目
    results.append({
        'id': aid,
        'title': title,
        'current_booklet': bc,
        'current_booklet_name': bn,
        'question': q,
        'text': txt,
        'len': len(txt)
    })

print(f"Loaded {len(results)} articles for V1 audit.")
